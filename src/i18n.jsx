import { create } from 'zustand';

// Thai is the source language: every UI string is written in Thai and wrapped
// in t(). In English mode t() looks it up here (falls back to the Thai text).
const KEY = 'meow-lang';
const initial = () => {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'th' || saved === 'en') return saved;
  } catch { /* ignore */ }
  return 'th'; // the team is Thai; English is one tap away
};

export const useLang = create((set) => ({
  lang: initial(),
  setLang: (lang) => {
    try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
    set({ lang });
  },
}));
if (typeof document !== 'undefined') document.documentElement.lang = useLang.getState().lang;

