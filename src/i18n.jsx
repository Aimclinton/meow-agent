const fmt = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`)) : s);

// Translate a Thai UI string. Works anywhere (components re-render when the
// language changes because App subscribes to useLang).
export function t(th, vars) {
  const lang = useLang.getState().lang;
  return fmt(lang === 'en' ? (EN[th] ?? th) : th, vars);
}

export function LangToggle({ className = '' }) {
  const lang = useLang((s) => s.lang);
  const setLang = useLang((s) => s.setLang);
  return (
    <button
      onClick={() => setLang(lang === 'th' ? 'en' : 'th')}
      className={`font-pixel text-[11px] px-1.5 h-6 rounded-[3px] border border-current/40 hover:bg-white/10 shrink-0 ${className}`}
      aria-label={lang === 'th' ? 'Switch to English' : 'เปลี่ยนเป็นภาษาไทย'}
    >
      <span className={lang === 'th' ? '' : 'opacity-40'}>TH</span>
      <span className="opacity-40">/</span>
      <span className={lang === 'en' ? '' : 'opacity-40'}>EN</span>
    </button>
  );
}
